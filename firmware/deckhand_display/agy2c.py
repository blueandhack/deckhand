#!/usr/bin/env python3
"""Generate AgyMark.h: the Antigravity session mark, 8 frames of 32x32 2-bit alpha.

    python3 agy2c.py > AgyMark.h

Same format as CodexMark.h and ClaudeSpark.h (rows of 8 bytes, 4 pixels a byte,
the leftmost pixel in the top two bits), tinted with the status colour at draw time,
so a frame is only ever an alpha mask.

ORIGINAL ART, deliberately: a thick upward chevron that LEVITATES over a short
ground line - the gap between them breathes across the cycle. It is not Google's
Antigravity logo and must not become one (this repo does not ship another company's
marks); the chevron-over-ground idea is ours, chosen because it reads as "lifting
off" at 32px and differs in silhouette from the Claude spark (radial) and the Codex
blob (round), which matters because shape, not colour, is what tells agents apart.

Drawn at 8x supersampling and box-filtered down, so the 2-bit alpha carries real
anti-aliasing rather than a hard staircase.
"""
import math

N = 32
SS = 8                      # supersampling factor
FRAMES = 8


def coverage(frame):
    """Per-pixel coverage 0..1 for one frame."""
    bob = 2.5 * math.sin(2 * math.pi * frame / FRAMES)  # px, + is up
    big = N * SS
    cov = [[0.0] * N for _ in range(N)]

    # Chevron: two thick strokes meeting at the apex, centred, raised by `bob`.
    apex = (16.0, 7.0 - bob)
    half_w = 10.5           # half the chevron's span
    drop = 9.5              # how far the arms fall below the apex
    thick = 3.6             # stroke half-thickness (px)
    left = (apex[0] - half_w, apex[1] + drop)
    right = (apex[0] + half_w, apex[1] + drop)

    def seg_dist(px, py, a, b):
        ax, ay = a; bx, by = b
        dx, dy = bx - ax, by - ay
        t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
        cx, cy = ax + t * dx, ay + t * dy
        return math.hypot(px - cx, py - cy)

    # Ground: a short rounded bar whose length shrinks a little as the chevron rises,
    # the "shadow" of the levitating mark.
    g_y = 26.0
    g_half = 7.0 - 1.2 * (bob / 2.5)
    g_thick = 1.6

    for sy in range(big):
        for sx in range(big):
            px = (sx + 0.5) / SS
            py = (sy + 0.5) / SS
            ink = (seg_dist(px, py, apex, left) <= thick or
                   seg_dist(px, py, apex, right) <= thick or
                   seg_dist(px, py, (16.0 - g_half, g_y), (16.0 + g_half, g_y)) <= g_thick)
            if ink:
                cov[sy // SS][sx // SS] += 1.0 / (SS * SS)
    return cov


def to_2bpp(cov):
    rows = []
    for y in range(N):
        out = []
        for bx in range(N // 4):
            byte = 0
            for k in range(4):
                a = int(round(cov[y][bx * 4 + k] * 3))
                byte |= (max(0, min(3, a)) << (6 - 2 * k))
            out.append(byte)
        rows.extend(out)
    return rows


def main():
    frames = [to_2bpp(coverage(f)) for f in range(FRAMES)]
    print("// Generated by agy2c.py - do not edit by hand.")
    print("// Antigravity 'working' animation: 8 frames, 32x32, 2 bits/pixel")
    print("// (alpha only - the firmware tints it with the status colour).")
    print("// An upward chevron levitating over a short ground line; ORIGINAL art, not")
    print("// Google's logo - see agy2c.py.")
    print("#pragma once")
    print("#include <pgmspace.h>")
    print(f"#define AGY_FRAMES {FRAMES}")
    print(f"#define AGY_SIZE   {N}")
    print(f"#define AGY_STRIDE {N // 4}")
    print(f"const uint8_t AGY_BITS[{FRAMES}][{N}*{N // 4}] PROGMEM = {{")
    for f in frames:
        print("  {" + ",".join(str(b) for b in f) + "},")
    print("};")


if __name__ == "__main__":
    main()
